"""
Build the portal's photo library: real, freely licensed photographs (Wikimedia Commons / Flickr,
found through Openverse) for listings without their own photos, societies, projects, stories and
page headers.

    python build_listing_photos.py            # download what's missing
    python build_listing_photos.py --force    # re-download everything

Input   geodata/pk_listing_photos.json — per category, the chosen photos with their credits
Output  frontend/public/seed/photos/<category>-<n>.webp and portable/public/seed/photos/… (960×720;
        the "scene" category — Islamabad page headers — at 1600×900)
        frontend/src/lib/photoLibrary.ts and portable/src/lib/photoLibrary.ts (generated)

Listings that use these photos are marked "Representative photo" in both apps; a listing's own
uploaded photos always win. Credits (author · licence · source) show on the listing page.
"""

from __future__ import annotations

import io
import json
import sys
import time
import urllib.request
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "backend" / "geodata" / "pk_listing_photos.json"
OUTS = [ROOT / "frontend" / "public" / "seed" / "photos", ROOT / "portable" / "public" / "seed" / "photos"]
TS_OUTS = [ROOT / "frontend" / "src" / "lib" / "photoLibrary.ts", ROOT / "portable" / "src" / "lib" / "photoLibrary.ts"]
UA = "ArzePakPortal/1.0 (https://github.com/Mubushar/arzepak-portal; photo library build)"
SIZE = (960, 720)
SCENE_SIZE = (1600, 900)  # page headers ("scene" category)

SITES = {"wikimedia": "Wikimedia Commons", "flickr": "Flickr", "rawpixel": "Rawpixel", "stocksnap": "StockSnap",
         "wordpress": "WordPress Photo Directory"}
LICENSES = {"by": "CC BY", "by-sa": "CC BY-SA", "cc0": "CC0", "pdm": "Public domain", "by-nd": "CC BY-ND"}


def _download_url(url: str, width: int = 1280) -> str:
    """A big-enough rendition: Wikimedia thumbnails (1280 px; 1920 for headers), Flickr's 1024 px size."""
    if "upload.wikimedia.org/wikipedia/commons/" in url and "/thumb/" not in url:
        tail = url.split("/wikipedia/commons/", 1)[1]
        name = tail.rsplit("/", 1)[1]
        if not name.lower().endswith((".svg", ".tif", ".tiff")):
            return f"https://upload.wikimedia.org/wikipedia/commons/thumb/{tail}/{width}px-{name}"
    return url


def _fetch(url: str) -> bytes:
    last: Exception | None = None
    for attempt in range(4):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA})
            return urllib.request.urlopen(req, timeout=60).read()
        except Exception as e:  # 429 / timeouts: back off
            last = e
            time.sleep(3 * (attempt + 1))
    raise RuntimeError(f"download failed: {url}: {last}")


def credit(p: dict) -> str:
    lic = LICENSES.get(p.get("license", ""), (p.get("license") or "").upper())
    ver = p.get("license_version")
    lic = f"{lic} {ver}" if ver and p.get("license") not in ("cc0", "pdm") else lic
    site = SITES.get(p.get("source", ""), p.get("source", ""))
    creator = p.get("creator") or ("" if site else "Unknown author")
    return " · ".join(x for x in [creator, lic, site] if x)


def main(force: bool = False) -> None:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    for out in OUTS:
        out.mkdir(parents=True, exist_ok=True)
    library: dict = {}
    for cat, photos in data["categories"].items():
        library[cat] = []
        for i, p in enumerate(photos, start=1):
            name = f"{cat}-{i}.webp"
            targets = [o / name for o in OUTS]
            if force or not all(t.exists() for t in targets):
                raw = _fetch(_download_url(p["url"], 1920 if cat == "scene" else 1280))
                im = ImageOps.exif_transpose(Image.open(io.BytesIO(raw))).convert("RGB")
                im = ImageOps.fit(im, SCENE_SIZE if cat == "scene" else SIZE, Image.LANCZOS, centering=tuple(p.get("focus", (0.5, 0.5))))
                buf = io.BytesIO()
                im.save(buf, "WEBP", quality=72, method=6)
                for t in targets:
                    t.write_bytes(buf.getvalue())
                print("saved", name, len(buf.getvalue()) // 1024, "KB")
                time.sleep(0.5)
            library[cat].append({"src": f"seed/photos/{name}", "title": p.get("title") or "", "credit": credit(p),
                                 "link": p.get("landing") or p["url"], "pakistan": bool(p.get("pakistan"))})
    body = json.dumps(library, indent=2, ensure_ascii=False)
    ts = ("// Generated by backend/build_listing_photos.py from backend/geodata/pk_listing_photos.json — do not edit.\n"
          "// Real, freely licensed photographs (Wikimedia Commons / Flickr), credited.\n"
          "export type LibraryPhoto = { src: string; title: string; credit: string; link: string; pakistan: boolean };\n\n"
          f"export const PHOTO_LIBRARY: Record<string, LibraryPhoto[]> = {body};\n")
    for t in TS_OUTS:
        t.write_text(ts, encoding="utf-8", newline="\n")
    print("library:", {k: len(v) for k, v in library.items()})


if __name__ == "__main__":
    main(force="--force" in sys.argv)
